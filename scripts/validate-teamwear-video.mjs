import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const read = (file) => readFile(path.join(root, file), "utf8");
const recipe = JSON.parse(await read("data/teamwear-video.json"));
const manifest = JSON.parse(await read("assets/videos/teamwear/manifest.json"));
const html = await read("teamwear/index.html");
const css = await read("assets/css/teamwear-story.css");
const runtime = await read("assets/js/hero-video.js");
assert.deepEqual([recipe.master.width, recipe.master.height, recipe.master.filter, recipe.master.codec], [2160, 3840, "spline36", "ffv1"]);
assert.deepEqual(recipe.variants.map(({ width, height }) => [width, height]), [[1080, 1920], [1440, 1440], [1920, 1080]]);
assert.equal(manifest.fps, "24000/1001");
assert.equal(manifest.sourceFrames, 540);
assert.equal(manifest.overlapFrames, 34);
for (const [index, output] of manifest.outputs.entries()) {
  const variant = recipe.variants[index];
  assert.equal(output.src, variant.src);
  const video = output.streams[0];
  assert.equal(output.streams.length, 1, "Web assets must not have audio tracks");
  assert.equal(video.codec_name, "h264");
  assert.deepEqual([video.width, video.height], [variant.width, variant.height]);
  assert.equal(Number(video.nb_frames), manifest.sourceFrames - manifest.overlapFrames);
  const bytes = await readFile(path.join(root, output.src));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), output.sha256);
  assert.ok(bytes.indexOf(Buffer.from("moov")) < bytes.indexOf(Buffer.from("mdat")), "MP4 must be fast-start");
  assert.ok((await readFile(path.join(root, output.poster))).length > 0);
  assert.ok(html.includes(output.src) && html.includes(output.poster));
}
const videoTag = html.match(/<video\b[^>]*>/)?.[0];
assert.ok(videoTag);
assert.match(videoTag, /muted loop playsinline preload="none"/);
assert.doesNotMatch(videoTag, /\ssrc=|\sautoplay/, "Defer fetching until motion/data/visibility checks pass");
assert.doesNotMatch(html, /teamwear-hero-master|assets\/temp\/10/);
assert.doesNotMatch(html, /data-hero-video-toggle|teamwear-hero__controls|teamwear-hero__toggle|Play background video|Pause background video/);
assert.doesNotMatch(css, /teamwear-hero__controls|teamwear-hero__toggle/);
assert.doesNotMatch(runtime, /data-hero-video-toggle|Play background video|Pause background video/);
assert.match(css, /\.teamwear-hero__media video\s*\{[^}]*object-fit:\s*cover;[^}]*opacity var\(--motion-duration-enter\) var\(--motion-ease-enter\)/);
assert.match(runtime, /requestVideoFrameCallback/);
assert.match(runtime, /prefers-reduced-motion/);
assert.match(runtime, /saveData/);
assert.match(runtime, /visibilitychange/);
assert.match(runtime, /IntersectionObserver/);
assert.doesNotMatch(runtime, /setInterval|setTimeout|currentTime\s*=/, "Looping must not rely on a JS seek timer");
